"""
The files of the project: `read_file`, `write_file` and `list_files`, within the project
directory, never `.env`, never written in what is installed, committed or generated.
"""

import pytest

from bazis.contrib.mcp import catalog, files, project

from .support import result
from .test_projects import error


pytestmark = pytest.mark.anyio

SECRET = 'value-of-the-secret'


@pytest.fixture
def shop(monkeypatch, tmp_path):
    directory = tmp_path / 'shop'
    (directory / 'shop').mkdir(parents=True)
    (directory / 'manage.py').write_text('')
    (directory / '.env').write_text(f'BS_SECRET_KEY={SECRET}\n')
    (tmp_path / 'secrets.txt').write_text(SECRET)
    monkeypatch.setattr(project, 'project_dir', directory)
    return directory


async def test_write_and_read_a_file(client, shop):
    written = result(await client.call_tool(
        'write_file', {'path': 'shop/catalog/models.py', 'content': 'name = "книга"\n'}
    ))
    assert written == {
        'path': 'shop/catalog/models.py', 'bytes': len('name = "книга"\n'.encode()), 'created': True
    }
    assert (shop / 'shop' / 'catalog' / 'models.py').read_text() == 'name = "книга"\n'

    read = result(await client.call_tool('read_file', {'path': 'shop/catalog/models.py'}))
    assert read == {'path': 'shop/catalog/models.py', 'content': 'name = "книга"\n'}

    # replaced; an absolute path in the project is the same file
    path = str(shop / 'shop' / 'catalog' / 'models.py')
    assert result(await client.call_tool('write_file', {'path': path, 'content': 'x = 1\n'}))[
        'created'] is False
    assert result(await client.call_tool('read_file', {'path': path}))['content'] == 'x = 1\n'
    # frontend/.env.local is not .env
    result(await client.call_tool(
        'write_file', {'path': 'frontend/.env.local', 'content': 'BAZIS_API_URL=http://localhost:8001\n'}
    ))


async def test_env_is_never_read_nor_written(client, shop):
    (shop / 'env-link').symlink_to(shop / '.env')
    for path in ('.env', 'env-link', str(shop / '.env'), 'shop/../.env'):
        call_result = await client.call_tool('read_file', {'path': path})
        assert error(call_result) == (
            '.env is never read: project_status gives the names of its variables.'
        ), path
        assert SECRET not in call_result.content[0].text
    for path in ('.env', 'env-link', 'frontend/.env'):
        message = error(await client.call_tool('write_file', {'path': path, 'content': 'X=1\n'}))
        assert message == '.env is written by the user only.', path
    assert (shop / '.env').read_text() == f'BS_SECRET_KEY={SECRET}\n'


async def test_the_names_in_another_case(client, shop):
    """
    `.env`, `.venv`, `.git`, `contract` and `generated` in another case are those names: on
    a file system that ignores the case they are the same entries.
    """
    (shop / 'frontend').mkdir()
    (shop / 'frontend' / '.ENV').write_text(f'TOKEN={SECRET}\n')
    for path in ('.ENV', '.Env', 'frontend/.ENV', 'frontend/.eNv'):
        call_result = await client.call_tool('read_file', {'path': path})
        assert error(call_result) in (
            '.env is never read: project_status gives the names of its variables.',
            f'{path} is not a file of the project.',  # a file system that minds the case
        ), path
        assert SECRET not in call_result.content[0].text
        message = error(await client.call_tool('write_file', {'path': path, 'content': 'X=1\n'}))
        assert message == '.env is written by the user only.', path
    assert (shop / '.env').read_text() == f'BS_SECRET_KEY={SECRET}\n'
    assert (shop / 'frontend' / '.ENV').read_text() == f'TOKEN={SECRET}\n'

    for path, message in (
        ('.VENV/lib/site.py', '.venv/ is installed (add_packages, run_command pip): it is never written.'),
        ('.Git/config', '.git/ is the repository of the user: it is never written.'),
        ('Contract/contract.json', 'contract/ is generated (bazis_front contract): it is never written.'),
        ('frontend/src/GENERATED/schema.d.ts',
         'A generated/ directory is generated by the bazis_front commands: it is never written.'),
    ):
        assert error(await client.call_tool('write_file', {'path': path, 'content': 'x'})) == message
        assert not (shop / path).exists()

    # listed by name and size, never read
    listed = result(await client.call_tool('list_files', {'subdir': 'frontend'}))
    assert listed['entries'] == [{'name': '.ENV', 'type': 'file', 'size': len(f'TOKEN={SECRET}\n')}]
    call_result = await client.call_tool('list_files', {'subdir': 'frontend/.ENV'})
    assert error(call_result) == 'frontend/.ENV is not a directory of the project.'
    assert SECRET not in call_result.content[0].text


async def test_a_hard_link_to_env(client, shop):
    (shop / 'shop' / 'settings.txt').hardlink_to(shop / '.env')
    call_result = await client.call_tool('read_file', {'path': 'shop/settings.txt'})
    assert error(call_result) == '.env is never read: project_status gives the names of its variables.'
    assert SECRET not in call_result.content[0].text
    message = error(await client.call_tool('write_file', {'path': 'shop/settings.txt', 'content': 'X'}))
    assert message == '.env is written by the user only.'
    assert (shop / '.env').read_text() == f'BS_SECRET_KEY={SECRET}\n'



@pytest.mark.parametrize('path, message', [
    ('.venv/lib/site.py', '.venv/ is installed (add_packages, run_command pip): it is never written.'),
    ('.git/config', '.git/ is the repository of the user: it is never written.'),
    ('contract/contract.json', 'contract/ is generated (bazis_front contract): it is never written.'),
    ('frontend/src/bazis/generated/schema.d.ts',
     'A generated/ directory is generated by the bazis_front commands: it is never written.'),
    ('frontend/e2e/generated/login.spec.ts',
     'A generated/ directory is generated by the bazis_front commands: it is never written.'),
    ('shop', 'shop is a directory.'),
    ('.', '. is a directory.'),
])
async def test_write_file_refusals(client, shop, path, message):
    assert error(await client.call_tool('write_file', {'path': path, 'content': 'x'})) == message
    assert not (shop / path).is_file()


async def test_the_paths_stay_in_the_project(client, shop, tmp_path):
    (shop / 'outside').symlink_to(tmp_path)
    for path in ('../secrets.txt', str(tmp_path / 'secrets.txt'), 'outside/secrets.txt',
                 '/etc/hosts'):
        for tool, args in (('read_file', {}), ('write_file', {'content': 'stolen'})):
            call_result = await client.call_tool(tool, {'path': path, **args})
            assert 'is outside the project directory' in error(call_result), (tool, path)
            assert SECRET not in call_result.content[0].text
    assert (tmp_path / 'secrets.txt').read_text() == SECRET
    for subdir in ('..', 'outside', str(tmp_path)):
        assert 'is outside the project directory' in error(
            await client.call_tool('list_files', {'subdir': subdir})
        )


async def test_the_sizes(client, shop, monkeypatch):
    (shop / 'big.txt').write_text('x' * (catalog.RESULT_LIMIT + 1))
    assert error(await client.call_tool('read_file', {'path': 'big.txt'})) == (
        f'big.txt has {catalog.RESULT_LIMIT + 1} bytes: read_file returns files up to '
        f'{catalog.RESULT_LIMIT}.'
    )
    # within the bytes, but not within a result: quotes and line ends are escaped in JSON
    (shop / 'quotes.txt').write_text('"\n' * (catalog.RESULT_LIMIT // 2))
    assert error(await client.call_tool('read_file', {'path': 'quotes.txt'})) == (
        'quotes.txt is too long for a result of read_file.'
    )
    (shop / 'image.png').write_bytes(b'\x89PNG\r\n\x1a\n\xff\xfe')
    assert error(await client.call_tool('read_file', {'path': 'image.png'})) == (
        'image.png is not a text file (UTF-8).'
    )
    assert error(await client.call_tool('read_file', {'path': 'missing.py'})) == (
        'missing.py is not a file of the project.'
    )

    monkeypatch.setattr(files, 'WRITE_LIMIT', 10)
    assert error(await client.call_tool('write_file', {'path': 'a.txt', 'content': 'x' * 11})) == (
        'The content has 11 bytes: write_file writes up to 10.'
    )
    assert not (shop / 'a.txt').exists()


async def test_list_files(client, shop, tmp_path, monkeypatch):
    (shop / 'shop' / 'models.py').write_text('x = 1\n')
    (shop / 'outside').symlink_to(tmp_path)

    listed = result(await client.call_tool('list_files', {}))
    assert listed == {
        'directory': '.',
        'entries': [
            {'name': '.env', 'type': 'file', 'size': len(f'BS_SECRET_KEY={SECRET}\n')},
            {'name': 'manage.py', 'type': 'file', 'size': 0},
            {'name': 'outside', 'type': 'link', 'size': None},  # never followed
            {'name': 'shop', 'type': 'directory', 'size': None},
        ],
        'truncated': False,
    }
    listed = result(await client.call_tool('list_files', {'subdir': 'shop'}))
    assert listed['directory'] == 'shop'
    assert listed['entries'] == [{'name': 'models.py', 'type': 'file', 'size': 6}]

    monkeypatch.setattr(files, 'LIST_LIMIT', 2)
    listed = result(await client.call_tool('list_files', {}))
    assert [it['name'] for it in listed['entries']] == ['.env', 'manage.py']
    assert listed['truncated'] is True

    assert error(await client.call_tool('list_files', {'subdir': 'manage.py'})) == (
        'manage.py is not a directory of the project.'
    )
