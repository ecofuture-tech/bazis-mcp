"""
The files of the project: `read_file`, `write_file`, `delete_file` and `list_files`, within
the project directory, never `.env`, never written nor deleted in what is installed,
committed or generated.
"""

import pytest

from bazis.contrib.mcp import catalog, files, project

from .support import result
from .test_projects import error


pytestmark = pytest.mark.anyio

SECRET = 'value-of-the-secret'


@pytest.fixture
def shop(monkeypatch, tmp_path):
    directory = tmp_path / 'shop'
    (directory / 'shop').mkdir(parents=True)
    (directory / 'manage.py').write_text('')
    (directory / '.env').write_text(f'BS_SECRET_KEY={SECRET}\n')
    (tmp_path / 'secrets.txt').write_text(SECRET)
    monkeypatch.setattr(project, 'project_dir', directory)
    return directory


async def test_write_and_read_a_file(client, shop):
    written = result(await client.call_tool(
        'write_file', {'path': 'shop/catalog/models.py', 'content': 'name = "книга"\n'}
    ))
    assert written == {
        'path': 'shop/catalog/models.py', 'bytes': len('name = "книга"\n'.encode()), 'created': True
    }
    assert (shop / 'shop' / 'catalog' / 'models.py').read_text() == 'name = "книга"\n'

    read = result(await client.call_tool('read_file', {'path': 'shop/catalog/models.py'}))
    assert read == {
        'path': 'shop/catalog/models.py', 'content': 'name = "книга"\n', 'next_offset': None
    }

    # replaced; an absolute path in the project is the same file
    path = str(shop / 'shop' / 'catalog' / 'models.py')
    assert result(await client.call_tool('write_file', {'path': path, 'content': 'x = 1\n'}))[
        'created'] is False
    assert result(await client.call_tool('read_file', {'path': path}))['content'] == 'x = 1\n'
    # frontend/.env.local is not .env
    result(await client.call_tool(
        'write_file', {'path': 'frontend/.env.local', 'content': 'BAZIS_API_URL=http://localhost:8001\n'}
    ))


async def test_env_is_never_read_nor_written(client, shop):
    (shop / 'env-link').symlink_to(shop / '.env')
    for path in ('.env', 'env-link', str(shop / '.env'), 'shop/../.env'):
        call_result = await client.call_tool('read_file', {'path': path})
        assert error(call_result) == (
            '.env is never read: project_status gives the names of its variables.'
        ), path
        assert SECRET not in call_result.content[0].text
    for path in ('.env', 'env-link', 'frontend/.env'):
        message = error(await client.call_tool('write_file', {'path': path, 'content': 'X=1\n'}))
        assert message == '.env is written by the user only.', path
    assert (shop / '.env').read_text() == f'BS_SECRET_KEY={SECRET}\n'


async def test_the_names_in_another_case(client, shop):
    """
    `.env`, `.venv`, `.git`, `contract` and `generated` in another case are those names: on
    a file system that ignores the case they are the same entries.
    """
    (shop / 'frontend').mkdir()
    (shop / 'frontend' / '.ENV').write_text(f'TOKEN={SECRET}\n')
    for path in ('.ENV', '.Env', 'frontend/.ENV', 'frontend/.eNv'):
        call_result = await client.call_tool('read_file', {'path': path})
        assert error(call_result) in (
            '.env is never read: project_status gives the names of its variables.',
            f'{path} is not a file of the project.',  # a file system that minds the case
        ), path
        assert SECRET not in call_result.content[0].text
        message = error(await client.call_tool('write_file', {'path': path, 'content': 'X=1\n'}))
        assert message == '.env is written by the user only.', path
    assert (shop / '.env').read_text() == f'BS_SECRET_KEY={SECRET}\n'
    assert (shop / 'frontend' / '.ENV').read_text() == f'TOKEN={SECRET}\n'

    for path, message in (
        ('.VENV/lib/site.py', '.venv/ is installed (add_packages, run_command pip): it is never written.'),
        ('.Git/config', '.git/ is the repository of the user: it is never written.'),
        ('Contract/contract.json', 'contract/ is generated (bazis_front contract): it is never written.'),
        ('frontend/src/GENERATED/schema.d.ts',
         'A generated/ directory is generated by the bazis_front commands: it is never written.'),
    ):
        assert error(await client.call_tool('write_file', {'path': path, 'content': 'x'})) == message
        assert not (shop / path).exists()

    # listed by name and size, never read
    listed = result(await client.call_tool('list_files', {'subdir': 'frontend'}))
    assert listed['entries'] == [{'name': '.ENV', 'type': 'file', 'size': len(f'TOKEN={SECRET}\n')}]
    call_result = await client.call_tool('list_files', {'subdir': 'frontend/.ENV'})
    assert error(call_result) == 'frontend/.ENV is not a directory of the project.'
    assert SECRET not in call_result.content[0].text


async def test_read_file_in_parts(client, shop):
    """
    A file longer than a result is read in parts, its lines from `offset`, at most `limit`;
    `next_offset` is the line to read next, null at the end.
    """
    line = 'x' * 99 + '\n'
    count = 2 * catalog.RESULT_LIMIT // len(line)
    (shop / 'long.txt').write_text(line * count)
    assert 'is too long' in error(await client.call_tool('read_file', {'path': 'long.txt'}))

    parts, offset = [], 0
    while offset is not None:
        read = result(await client.call_tool(
            'read_file', {'path': 'long.txt', 'offset': offset, 'limit': count // 3 + 1}
        ))
        parts.append(read['content'])
        offset = read['next_offset']
    assert len(parts) == 3 and ''.join(parts) == line * count

    (shop / 'lines.txt').write_text('a\nb\nc\n')
    read = result(await client.call_tool('read_file', {'path': 'lines.txt', 'offset': 1, 'limit': 1}))
    assert read == {'path': 'lines.txt', 'content': 'b\n', 'next_offset': 2}
    read = result(await client.call_tool('read_file', {'path': 'lines.txt', 'offset': 1}))
    assert read == {'path': 'lines.txt', 'content': 'b\nc\n', 'next_offset': None}
    read = result(await client.call_tool('read_file', {'path': 'lines.txt', 'offset': 3, 'limit': 5}))
    assert read == {'path': 'lines.txt', 'content': '', 'next_offset': None}
    for args in ({'offset': -1}, {'limit': 0}):
        assert (await client.call_tool('read_file', {'path': 'lines.txt', **args})).is_error


