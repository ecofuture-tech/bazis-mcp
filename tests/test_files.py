async def test_the_paths_stay_in_the_project(client, shop, tmp_path):
    (shop / 'outside').symlink_to(tmp_path)
    for path in ('../secrets.txt', str(tmp_path / 'secrets.txt'), 'outside/secrets.txt',
                 '/etc/hosts'):
        for tool, args in (('read_file', {}), ('write_file', {'content': 'stolen'})):
            call_result = await client.call_tool(tool, {'path': path, **args})
            assert 'is outside the project directory' in error(call_result), (tool, path)
            assert SECRET not in call_result.content[0].text
    assert (tmp_path / 'secrets.txt').read_text() == SECRET
    for subdir in ('..', 'outside', str(tmp_path)):
        assert 'is outside the project directory' in error(
            await client.call_tool('list_files', {'subdir': subdir})
        )


async def test_the_sizes(client, shop, monkeypatch):
    in_parts = 'read it in parts (fewer lines) with offset and limit.'
    (shop / 'big.txt').write_text('x' * (catalog.RESULT_LIMIT + 1))
    assert error(await client.call_tool('read_file', {'path': 'big.txt'})) == (
        f'big.txt is too long for a result of read_file: {in_parts}'
    )
    # within the bytes, but not within a result: quotes and line ends are escaped in JSON
    (shop / 'quotes.txt').write_text('"\n' * (catalog.RESULT_LIMIT // 2))
    assert error(await client.call_tool('read_file', {'path': 'quotes.txt'})) == (
        f'quotes.txt is too long for a result of read_file: {in_parts}'
    )
    assert error(await client.call_tool(
        'read_file', {'path': 'quotes.txt', 'offset': 10, 'limit': catalog.RESULT_LIMIT // 2}
    )) == f'quotes.txt is too long for a result of read_file: {in_parts}'
    (shop / 'image.png').write_bytes(b'\x89PNG\r\n\x1a\n\xff\xfe')
    assert error(await client.call_tool('read_file', {'path': 'image.png'})) == (
        'image.png is not a text file (UTF-8).'
    )
    assert error(await client.call_tool('read_file', {'path': 'missing.py'})) == (
        'missing.py is not a file of the project.'
    )

    monkeypatch.setattr(files, 'WRITE_LIMIT', 10)
    assert error(await client.call_tool('write_file', {'path': 'a.txt', 'content': 'x' * 11})) == (
        'The content has 11 bytes: write_file writes up to 10.'
    )
    assert not (shop / 'a.txt').exists()


async def test_delete_file(client, shop):
    spec = shop / 'frontend' / 'e2e' / 'custom' / 'screenshots.spec.ts'
    spec.parent.mkdir(parents=True)
    spec.write_text('x')
    path = 'frontend/e2e/custom/screenshots.spec.ts'
    assert result(await client.call_tool('delete_file', {'path': path})) == {'path': path, 'link': False}
    assert not spec.exists() and spec.parent.is_dir()
    assert error(await client.call_tool('delete_file', {'path': path})) == (
        f'{path} is not a file of the project.'
    )
    assert error(await client.call_tool('delete_file', {'path': 'missing.py'})) == (
        'missing.py is not a file of the project.'
    )

    # an absolute path in the project; any file that write_file writes
    for name in ('notes.txt', 'manage.py', 'requirements.txt'):
        (shop / name).write_text('')
        deleted = result(await client.call_tool('delete_file', {'path': str(shop / name)}))
        assert deleted == {'path': name, 'link': False}
        assert not (shop / name).exists()

    # a symbolic link is deleted itself, never what it links to
    (shop / 'shop' / 'models.py').write_text('x = 1\n')
    (shop / 'models-link.py').symlink_to(shop / 'shop' / 'models.py')
    deleted = result(await client.call_tool('delete_file', {'path': 'models-link.py'}))
    assert deleted == {'path': 'models-link.py', 'link': True}
    assert not (shop / 'models-link.py').is_symlink()
    assert (shop / 'shop' / 'models.py').read_text() == 'x = 1\n'
    # a link to nothing is not a file, a link to a directory is a directory: both stay
    (shop / 'dangling').symlink_to(shop / 'missing.py')
    assert error(await client.call_tool('delete_file', {'path': 'dangling'})) == (
        'dangling is not a file of the project.'
    )
    (shop / 'shop-link').symlink_to(shop / 'shop')
    assert error(await client.call_tool('delete_file', {'path': 'shop-link'})) == (
        'shop-link is a directory.'
    )
    assert (shop / 'dangling').is_symlink() and (shop / 'shop-link').is_symlink()


@pytest.mark.parametrize('path, existing, message', [
    ('shop', None, 'shop is a directory.'),
    ('.', None, '. is a directory.'),
    ('shop/..', None, 'shop/.. is a directory.'),
    ('.env', None, '.env is written by the user only.'),
    ('.ENV', '.env', '.env is written by the user only.'),
    ('frontend/.Env', None, '.env is written by the user only.'),
    ('.venv/lib/site.py', None,
     '.venv/ is installed (add_packages, run_command pip): it is never written.'),
    ('.VENV/lib/site.py', '.venv/lib/site.py',
     '.venv/ is installed (add_packages, run_command pip): it is never written.'),
    ('.Git/config', '.git/config', '.git/ is the repository of the user: it is never written.'),
    ('contract/contract.json', None,
     'contract/ is generated (bazis_front contract): it is never written.'),
    ('frontend/src/bazis/Generated/schema.d.ts', 'frontend/src/bazis/generated/schema.d.ts',
     'A generated/ directory is generated by the bazis_front commands: it is never written.'),
])
async def test_delete_file_refusals(client, shop, path, existing, message):
    """
    The files never written are never deleted, the names in any case: on a file system that
    ignores the case `existing` is the same file.
    """
    file = shop / (existing or path)
    if not file.is_dir():
        file.parent.mkdir(parents=True, exist_ok=True)
        file.write_text('x')
    assert error(await client.call_tool('delete_file', {'path': path})) == message
    assert file.exists()


async def test_delete_file_stays_in_the_project(client, shop, tmp_path):
    (shop / 'outside').symlink_to(tmp_path)
    (shop / 'secrets-link').symlink_to(tmp_path / 'secrets.txt')
    for path in ('../secrets.txt', str(tmp_path / 'secrets.txt'), 'outside/secrets.txt',
                 'secrets-link', 'shop/../../secrets.txt', '..', '/etc/hosts'):
        message = error(await client.call_tool('delete_file', {'path': path}))
        assert 'is outside the project directory' in message, path
    assert (tmp_path / 'secrets.txt').read_text() == SECRET
    assert (shop / 'secrets-link').is_symlink()


async def test_list_files(client, shop, tmp_path, monkeypatch):
    (shop / 'shop' / 'models.py').write_text('x = 1\n')
    (shop / 'outside').symlink_to(tmp_path)

    listed = result(await client.call_tool('list_files', {}))
    assert listed == {
        'directory': '.',
        'entries': [
            {'name': '.env', 'type': 'file', 'size': len(f'BS_SECRET_KEY={SECRET}\n')},
            {'name': 'manage.py', 'type': 'file', 'size': 0},
            {'name': 'outside', 'type': 'link', 'size': None},  # never followed
            {'name': 'shop', 'type': 'directory', 'size': None},
        ],
        'truncated': False,
    }
    listed = result(await client.call_tool('list_files', {'subdir': 'shop'}))
    assert listed['directory'] == 'shop'
    assert listed['entries'] == [{'name': 'models.py', 'type': 'file', 'size': 6}]

    monkeypatch.setattr(files, 'LIST_LIMIT', 2)
    listed = result(await client.call_tool('list_files', {}))
    assert [it['name'] for it in listed['entries']] == ['.env', 'manage.py']
    assert listed['truncated'] is True

    assert error(await client.call_tool('list_files', {'subdir': 'manage.py'})) == (
        'manage.py is not a directory of the project.'
    )
