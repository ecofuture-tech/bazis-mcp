"""
The files of the project served, for a client without files of its own: read, written and
listed within the project directory only (`project.inside`, symbolic links resolved).
`.env` is never read nor written; `.venv/`, `.git/`, `contract/` and the `generated/`
directories are never written (installed, committed by the user, generated). These names
are compared whatever their case, and an existing file with the same file system entry as
one of them (another case on a file system that ignores it, a hard link) is that one.
"""

import os
from pathlib import Path

from . import catalog, project


#: the top directories of the project that are never written, and why
NOT_WRITTEN = {
    '.venv': 'is installed (add_packages, run_command pip)',
    '.git': 'is the repository of the user',
    'contract': 'is generated (bazis_front contract)',
}
#: the longest content of `write`, in bytes
WRITE_LIMIT = 1_000_000
#: the most entries of `listing`
LIST_LIMIT = 400


def _relative(path: Path) -> str:
    return path.relative_to(project.project_dir).as_posix() or '.'


def _same(path: Path, other: Path) -> bool:
    try:
        return os.path.samefile(path, other)
    except OSError:
        return False


def _named(path: Path, name: str) -> bool:
    """
    Whether `path` is the entry `name` (lower case) of its directory: by its name in any
    case, or as the same file.
    """
    return path.name.casefold() == name or _same(path, path.parent / name)


def _secret(path: Path) -> bool:
    return _named(path, '.env') or _same(path, project.project_dir / '.env')


def read(path: str, offset: int = 0, limit: int | None = None) -> dict:
    """
    The text of the file `path` of the project (UTF-8): its lines from `offset` (the first
    is 0), at most `limit` of them (default: to the end), when the result fits in
    `catalog.RESULT_LIMIT`. `next_offset` is the first line not read, None at the end.
    """
    target = project.inside(path)
    if _secret(target):
        raise project.ProjectError('.env is never read: project_status gives the names of its variables.')
    if not target.is_file():
        raise project.ProjectError(f'{path} is not a file of the project.')
    lines: list[str] = []
    next_offset = None
    size = 0
    try:
        with target.open(encoding='utf-8') as file:
            for number, line in enumerate(file):
                if number < offset:
                    continue
                if limit is not None and len(lines) == limit:
                    next_offset = number
                    break
                lines.append(line)
                size += len(line)
                if size > catalog.RESULT_LIMIT:
                    break  # refused below, without reading the rest
    except UnicodeDecodeError:
        raise project.ProjectError(f'{path} is not a text file (UTF-8).') from None
    result = {'path': _relative(target), 'content': ''.join(lines), 'next_offset': next_offset}
    if catalog.json_size(result) > catalog.RESULT_LIMIT:
        raise project.ProjectError(
            f'{path} is too long for a result of read_file: read it in parts (fewer lines) with '
            'offset and limit.'
        )
    return result


def refusal(target: Path) -> str | None:
    """
    Why the file `target` (a path of `project.inside`) is not written, or None.
    """
    parts = Path(_relative(target)).parts
    if not parts or target.is_dir():
        return f'{_relative(target)} is a directory.'
    if _secret(target):
        return '.env is written by the user only.'
    for name, reason in NOT_WRITTEN.items():
        if _named(project.project_dir / parts[0], name):
            return f'{name}/ {reason}: it is never written.'
    for depth in range(1, len(parts)):
        if _named(project.project_dir.joinpath(*parts[:depth]), 'generated'):
            return 'A generated/ directory is generated by the bazis_front commands: it is never written.'
    return None


def write(path: str, content: str) -> dict:
    """
    Writes `content` (UTF-8, at most WRITE_LIMIT bytes) to the file `path` of the project,
    with its missing directories, unless `refusal` refuses it.
    """
    target = project.inside(path)
    if problem := refusal(target):
        raise project.ProjectError(problem)
    data = content.encode()
    if len(data) > WRITE_LIMIT:
        raise project.ProjectError(f'The content has {len(data)} bytes: write_file writes up to {WRITE_LIMIT}.')
    created = not target.exists()
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(data)
    return {'path': _relative(target), 'bytes': len(data), 'created': created}


def listing(subdir: str = '') -> dict:
    """
    The entries of the directory `subdir` of the project (default: the project directory),
    by name, at most LIST_LIMIT: `name`, `type` (`directory`, `file`, `link`, never
    followed, or `other`) and the `size` of a file.
    """
    directory = project.inside(subdir or '.')
    if not directory.is_dir():
        raise project.ProjectError(f'{subdir} is not a directory of the project.')
    entries = []
    for entry in sorted(directory.iterdir(), key=lambda it: it.name):
        if entry.is_symlink():
            kind = 'link'
        elif entry.is_dir():
            kind = 'directory'
        else:
            kind = 'file' if entry.is_file() else 'other'
        entries.append({
            'name': entry.name, 'type': kind,
            'size': entry.stat().st_size if kind == 'file' else None,
        })
    return {
        'directory': _relative(directory),
        'entries': entries[:LIST_LIMIT],
        'truncated': len(entries) > LIST_LIMIT,
    }
